package com.invisiblejourney.domain

import com.invisiblejourney.domain.model.ConditionReading
import com.invisiblejourney.domain.model.JourneyRecord
import com.invisiblejourney.domain.model.MountType
import com.invisiblejourney.domain.model.Phase
import com.invisiblejourney.domain.model.SourceTag
import com.invisiblejourney.domain.processor.G
import com.invisiblejourney.domain.processor.Geo
import com.invisiblejourney.domain.processor.IndianAqi
import java.time.ZoneId
import java.time.ZonedDateTime
import kotlin.math.cos
import kotlin.math.max
import kotlin.math.min
import kotlin.math.sqrt
import kotlin.random.Random

/**
 * Synthetic but realistic journeys for Demo mode. They are generated by running simulated
 * sensor data through the real [JourneyEngine], so they exercise exactly the same code as a live ride.
 * Clearly marked `isSample = true` so they are never mistaken for real rider data.
 */
object SampleJourneys {

    enum class Scenario(val title: String) {
        HOT_AFTERNOON("Sample · Hot, hazy afternoon"),
        MONSOON_EVENING("Sample · Monsoon evening"),
    }

    // Koramangala → HSR Layout, Bengaluru (approximate street path).
    private val toStore = listOf(12.9330 to 77.6180, 12.9341 to 77.6212, 12.9352 to 77.6245)
    private val toCustomer = listOf(
        12.9352 to 77.6245, 12.9327 to 77.6258, 12.9300 to 77.6270, 12.9272 to 77.6286,
        12.9245 to 77.6300, 12.9222 to 77.6326, 12.9200 to 77.6350, 12.9182 to 77.6380,
        12.9165 to 77.6410, 12.9130 to 77.6440, 12.9115 to 77.6455,
    )

    private class Stop(val atFraction: Double, val seconds: Int, val signal: Boolean)

    private val STOPS = listOf(Stop(0.25, 70, true), Stop(0.55, 50, true), Stop(0.80, 35, false))

    /**
     * One simulated second of a ride: where the rider is, plus 50 vertical-acceleration samples
     * (m/s², 20 ms apart). [advancePhaseAfter] marks where the rider would tap the phase button.
     */
    class RideFrame(
        val lat: Double,
        val lng: Double,
        val speedKmh: Float,
        val imu: FloatArray,
        val advancePhaseAfter: Boolean = false,
    )

    /** The second-by-second sensor script for a scenario. Used for samples and for live simulated rides. */
    fun script(scenario: Scenario): List<RideFrame> {
        val rnd = Random(scenario.ordinal + 7)
        val frames = mutableListOf<RideFrame>()

        fun emitSecond(lat: Double, lng: Double, speedKmh: Float, roughSd: Float, potholeG: Float?) {
            val jLat = lat + rnd.nextDouble(-1.5, 1.5) / 111_320.0
            val jLng = lng + rnd.nextDouble(-1.5, 1.5) / (111_320.0 * cos(Math.toRadians(lat)))
            val imu = FloatArray(50) { i ->
                when {
                    potholeG != null && i == 25 -> potholeG * G
                    potholeG != null && i == 27 -> -0.6f * potholeG * G
                    else -> gaussian(rnd) * (if (speedKmh > 1f) roughSd else 0.08f)
                }
            }
            frames += RideFrame(jLat, jLng, speedKmh, imu)
        }

        fun markPhaseChange() {
            val f = frames.removeAt(frames.lastIndex)
            frames += RideFrame(f.lat, f.lng, f.speedKmh, f.imu, advancePhaseAfter = true)
        }

        fun ride(path: List<Pair<Double, Double>>, cruiseKmh: Float, withEvents: Boolean) {
            val cum = DoubleArray(path.size)
            for (i in 1 until path.size) {
                cum[i] = cum[i - 1] + Geo.distanceM(path[i - 1].first, path[i - 1].second, path[i].first, path[i].second)
            }
            val total = cum.last()
            val potholes = if (withEvents) mutableListOf(0.15, 0.42, 0.62, 0.66, 0.70, 0.88) else mutableListOf()
            val pendingStops = if (withEvents) STOPS.toMutableList() else mutableListOf()
            var d = 0.0
            var v = 0.0 // m/s
            while (d < total) {
                val f = d / total
                val (lat, lng) = pointAt(path, cum, d)
                val stop = pendingStops.firstOrNull { f >= it.atFraction }
                if (stop != null) {
                    pendingStops.remove(stop)
                    repeat(stop.seconds) { emitSecond(lat, lng, 0f, 0.1f, null) }
                    v = 0.0
                    continue
                }
                val target = when {
                    withEvents && f in 0.35..0.50 -> 9.0 // congested stretch
                    withEvents && f in 0.60..0.75 -> 14.0 // broken road
                    else -> cruiseKmh.toDouble()
                } / 3.6 + rnd.nextDouble(-0.6, 0.6)
                v = if (v < target) min(target, v + 1.2) else max(target, v - 2.0)
                val roughSd = when {
                    withEvents && f in 0.60..0.75 -> 2.3f
                    withEvents && f in 0.35..0.50 -> 1.3f
                    else -> 0.5f
                }
                val hit = potholes.firstOrNull { it <= f }
                if (hit != null) potholes.remove(hit)
                emitSecond(lat, lng, (v * 3.6).toFloat(), roughSd, hit?.let { 1.9f + rnd.nextFloat() * 1.6f })
                d += v
            }
        }

        fun wait(seconds: Int, at: Pair<Double, Double>) =
            repeat(seconds) { emitSecond(at.first, at.second, 0f, 0.1f, null) }

        ride(toStore, cruiseKmh = 22f, withEvents = false)
        markPhaseChange() // → AT_STORE
        wait(if (scenario == Scenario.HOT_AFTERNOON) 300 else 380, toStore.last())
        markPhaseChange() // → EN_ROUTE
        ride(toCustomer, cruiseKmh = if (scenario == Scenario.MONSOON_EVENING) 18f else 25f, withEvents = true)
        markPhaseChange() // → ARRIVED
        wait(170, toCustomer.last())
        markPhaseChange() // → DELIVERED
        return frames
    }

    fun generate(scenario: Scenario): JourneyRecord {
        val rnd = Random(scenario.ordinal + 99)
        val zone = ZoneId.of("Asia/Kolkata")
        val start = when (scenario) {
            Scenario.HOT_AFTERNOON -> ZonedDateTime.of(2026, 5, 14, 14, 20, 0, 0, zone)
            Scenario.MONSOON_EVENING -> ZonedDateTime.of(2026, 7, 22, 19, 5, 0, 0, zone)
        }.toInstant().toEpochMilli()

        lateinit var engine: JourneyEngine
        val requests = object : EngineRequests {
            var count = 0
            override fun checkSignal(stopId: Int, lat: Double, lng: Double) {
                val signal = STOPS.getOrNull(count++)?.signal ?: false
                engine.onSignalResult(stopId, signal)
            }
            override fun fetchFreeFlow(segmentId: Int, lat: Double, lng: Double) = Unit
        }
        engine = JourneyEngine(
            id = "sample-${scenario.name.lowercase()}",
            title = scenario.title,
            startedAt = start,
            promisedEtaMin = 10,
            mount = MountType.HANDLEBAR,
            requests = requests,
            isSample = true,
        )

        fun conditionsAt(time: Long): ConditionReading {
            val (temp, feels, pm25, pm10, precip, code) = when (scenario) {
                Scenario.HOT_AFTERNOON -> Sextuple(34.5f, 39.5f, 78f, 142f, 0f, 2)
                Scenario.MONSOON_EVENING -> Sextuple(23.0f, 25.0f, 31f, 58f, 2.4f, 63)
            }
            val wiggle = rnd.nextDouble(-0.6, 0.6).toFloat()
            return ConditionReading(
                t = time, source = SourceTag.API, tempC = temp + wiggle, feelsLikeC = feels + wiggle,
                humidityPct = if (precip > 0) 92f else 38f, precipitationMm = precip, weatherCode = code,
                windKmh = 9f, isDay = scenario == Scenario.HOT_AFTERNOON, pm25 = pm25, pm10 = pm10,
                aqi = IndianAqi.compute(pm25, pm10),
            )
        }

        var t = start
        engine.onConditions(conditionsAt(t))
        var lastConditions = t
        for (f in script(scenario)) {
            engine.onLocation(t, f.lat, f.lng, accuracyM = 6f, rawSpeedKmh = f.speedKmh)
            f.imu.forEachIndexed { i, az -> engine.onImu(t + i * 20L, az) }
            t += 1_000
            engine.onTick(t)
            if (t - lastConditions >= 10 * 60_000) {
                engine.onConditions(conditionsAt(t))
                lastConditions = t
            }
            if (f.advancePhaseAfter) engine.advancePhase(t)
        }
        check(engine.phase == Phase.DELIVERED)
        return engine.record()
    }

    private fun pointAt(path: List<Pair<Double, Double>>, cum: DoubleArray, d: Double): Pair<Double, Double> {
        val i = (1 until path.size).firstOrNull { cum[it] >= d } ?: (path.size - 1)
        val segLen = cum[i] - cum[i - 1]
        val k = if (segLen > 0) (d - cum[i - 1]) / segLen else 0.0
        val a = path[i - 1]
        val b = path[i]
        return Pair(a.first + (b.first - a.first) * k, a.second + (b.second - a.second) * k)
    }

    private fun gaussian(rnd: Random): Float {
        // Box–Muller
        val u1 = rnd.nextDouble().coerceAtLeast(1e-9)
        val u2 = rnd.nextDouble()
        return (sqrt(-2.0 * kotlin.math.ln(u1)) * cos(2 * Math.PI * u2)).toFloat()
    }

    private data class Sextuple(val a: Float, val b: Float, val c: Float, val d: Float, val e: Float, val f: Int)
}
